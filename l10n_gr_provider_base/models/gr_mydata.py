# Types offered regardless of partner class (credit notes, dispatch, self-use,
# titles, contracts, POS receipts, and all accounting entries not mapped above).
CLASS_AGNOSTIC_TYPES = frozenset(
    t for t, _ in INVOICE_TYPES) - set(INV_TYPE_PARTNER_CLASS)


def partner_class(is_company, country_code, eu_country_codes, has_vat):
    """Derive the partner class from Odoo's is_company + country.

    ponytail: pure function, no ORM — testable and reused by move + journal.
    eu_country_codes: iterable of ISO codes considered EU (excl. GR).
    """
    cc = (country_code or '').upper()
    if cc and cc != 'GR':
        return 'eu' if cc in eu_country_codes else 'third'
    # domestic (GR or unset): company vs individual
    return 'b2b' if (is_company or has_vat) else 'retail'


def journal_types_for_class(cls):
    """Invoice types a given partner class may use (mapped + agnostic)."""
    return CLASS_AGNOSTIC_TYPES | {
        t for t, classes in INV_TYPE_PARTNER_CLASS.items() if cls in classes
    }


