def default_classification(inv_type, product_type):
    """Derive the default (category, E3) for an invoice type + product type.

    Picks the product type's preferred income category if the invoice type
    allows it (else the first available income category), then the first valid
    E3 code for that combo. Returns (None, None) when the type has no directly
    derivable classification (e.g. 5.1, which follows the correlated original).
    """
    cats = valid_cls_categories(inv_type)
    if not cats:
        return (None, None)
    cat = PT_CATEGORY.get(product_type)
    if cat not in cats:
        income = sorted(c for c in cats if c.startswith('category1_'))
        cat = income[0] if income else sorted(cats)[0]
    e3s = sorted(valid_cls_types(inv_type, cat))
    return (cat, e3s[0] if e3s else None)


