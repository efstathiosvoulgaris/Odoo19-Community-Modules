def valid_cls_categories(inv_type):
    """Return frozenset of classification categories allowed for an invoice type."""
    return frozenset(CLASSIFICATION_MAP.get(inv_type, {}))


def valid_cls_types(inv_type, category):
    """Return frozenset of valid E3 codes for an invoice type + category combo."""
    type_map = CLASSIFICATION_MAP.get(inv_type, {})
    types = type_map.get(category)
    if not types or types == 'blank':
        return frozenset()
    if types == 'all_above':
        # Union of all tuple entries in the same category group (category1_* or category2_*)
        prefix = category[:9]  # 'category1' or 'category2'
        result = set()
        for cat, val in type_map.items():
            if cat.startswith(prefix) and isinstance(val, tuple):
                result.update(val)
        return frozenset(result)
    return frozenset(types)


