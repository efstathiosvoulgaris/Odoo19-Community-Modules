RETAIL_E3_PREFERENCE = ('E3_561_003', 'E3_880_002')


def default_classification(inv_type, product_type):
    """Derive the default (category, E3) for an invoice type + product type.

    Picks the product type's preferred income category if the invoice type
    allows it (else the first available income category), then the preferred
    valid E3 code for that combo (retail codes on 11.x, else first valid).
    Returns (None, None) when the type has no directly derivable
    classification (e.g. 5.1, which follows the correlated original).
    """
    cats = valid_cls_categories(inv_type)
    if not cats:
        return (None, None)
    cat = PT_CATEGORY.get(product_type)
    if cat not in cats:
        income = sorted(c for c in cats if c.startswith('category1_'))
        cat = income[0] if income else sorted(cats)[0]
    return (cat, preferred_e3(inv_type, valid_cls_types(inv_type, cat)))


def preferred_e3(inv_type, e3s):
    """Best default E3 from a valid set: retail codes on 11.x, else first."""
    if not e3s:
        return None
    if inv_type.startswith('11.'):
        for preferred in RETAIL_E3_PREFERENCE:
            if preferred in e3s:
                return preferred
    return sorted(e3s)[0]


